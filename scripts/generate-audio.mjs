// Pre-generates the examiner's voice for every question (dev-time, not deployed):
//   OPENAI_API_KEY=sk-... node scripts/generate-audio.mjs
// Writes public/audio/<hash>.mp3 (32 kbps mono, needs ffmpeg) and the manifest
// tgcloud/lib/audio-manifest.js. Existing clips are reused, so re-running only
// fills in new questions.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { allTests, buildSteps, spokenText } from '../tgcloud/lib/exam.js';

const VOICE = process.env.TTS_VOICE ?? 'sage';
const INSTRUCTIONS = 'You are a calm, friendly English speaking examiner. Speak clearly at a natural, slightly slow exam pace.';
const OUT = 'public/audio';
mkdirSync(OUT, { recursive: true });

const texts = [...new Set(allTests().flatMap((t) => buildSteps(t).map(spokenText)))];
const manifest = {};
let made = 0;
for (const text of texts) {
  const file = createHash('sha1').update(`${VOICE}|${text}`).digest('hex').slice(0, 12) + '.mp3';
  manifest[text] = file;
  if (existsSync(`${OUT}/${file}`)) continue;
  for (let attempt = 1; ; attempt++) {
    const res = await fetch('https://api.openai.com/v1/audio/speech', {
      method: 'POST',
      headers: { Authorization: `Bearer ${process.env.OPENAI_API_KEY}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ model: 'gpt-4o-mini-tts', voice: VOICE, input: text, instructions: INSTRUCTIONS, response_format: 'mp3' }),
    });
    if (res.ok) {
      const raw = `${OUT}/.${file}`;
      writeFileSync(raw, Buffer.from(await res.arrayBuffer()));
      execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', raw, '-ac', '1', '-b:a', '32k', `${OUT}/${file}`]);
      execFileSync('rm', [raw]);
      made++;
      break;
    }
    if (attempt >= 3) throw new Error(`TTS failed (${res.status}) for: ${text}\n${await res.text()}`);
    await new Promise((r) => setTimeout(r, 2000 * attempt));
  }
  process.stdout.write(`\r${Object.keys(manifest).length}/${texts.length}`);
}
const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync('tgcloud/lib/audio-manifest.js',
  `// Generated by scripts/generate-audio.mjs: spoken text → clip in public/audio/.\nexport default ${JSON.stringify(sorted, null, 1)};\n`);
console.log(`\n${texts.length} clips (${made} new) → ${OUT}/`);
