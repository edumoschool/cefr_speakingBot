const DICTS: Record<Lang, Dict> = { en, uz, ru };
export type TKey = keyof Dict;
export type T = (key: TKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = DICTS[lang] ?? en;
  return (key, vars) => {
    let s = d[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** First guess before the server answers: Telegram's interface language. */
export function detectLang(): Lang {
  const code = tg?.initDataUnsafe?.user?.language_code;
  const nav = code || (typeof navigator !== 'undefined' ? navigator.language : 'en');
  if (/^uz/i.test(nav ?? '')) return 'uz';
  if (/^(ru|kk|ky|tg|be|uk)/i.test(nav ?? '')) return 'ru';
  return 'en';
}

export const I18n = createContext<{ lang: Lang; t: T; setLang: (l: Lang) => void }>({
  lang: 'en',
  t: makeT('en'),
  setLang: () => undefined,
});

export const useI18n = () => useContext(I18n);

/** Human message for an API error code (codes come from tgcloud EndpointErrors). */
export function errorText(t: T, e: unknown): string {
  const code = (e as { code?: string })?.code;
  const map: Record<string, TKey> = {
    NO_TELEGRAM: 'errNoTelegram',
    NO_ATTEMPTS: 'errNoAttempts',
    ACTIVE_SESSION: 'errActive',
    NO_DRILLS: 'errNoDrills',
    EXPIRED: 'errExpired',
    BUSY: 'errBusy',
    NO_ANSWERS: 'errNoAnswers',
    PAYMENTS_OFF: 'errPaymentsOff',
    NOT_MEMBER: 'errNotMember',
  };
  return t(code && map[code] ? map[code] : 'errNetwork');
}

